#!/usr/bin/env node
// Writes fixtures/intl/de and fixtures/intl/ja for every agent: the CSV files of
// its first spreadsheet eval case as a German export (Windows-1252, semicolons,
// comma decimals, dotted dates, kg and km) and a Japanese one (Shift_JIS, year-first
// dates), and adds eval cases "intl-de-<id>" and "intl-ja-<id>" with the same
// expectations. Run again after changing a fixture; --check exits 1 when stale.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { kindsByArg } from '../packages/fairwire-core/src/index.js';
import { MARKETS, localise, argFiles } from './lib/localise.mjs';
import { encodeText } from './lib/encode.mjs';

const PK = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages');
const check = process.argv.includes('--check');
const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
let stale = 0;
const README = `# Fixtures from other countries

Generated by \`node scripts/make-intl-fixtures.mjs\` from the English fixtures one
folder up. The same fictional data, written the way a local export writes it:

- \`de/\`: German column names, Windows-1252 text, semicolons, comma decimals
  (1.234,56), day-first dotted dates (03.11.2026), kilograms and kilometres.
- \`ja/\`: Japanese column names, Shift_JIS text, year-first dates (2026/11/03),
  kilograms and kilometres.

Values (names, codes, charge wording) stay in English. The eval cases
\`intl-de-*\` and \`intl-ja-*\` expect exactly the same results as the English case.
`;
for (const n of readdirSync(PK).filter((x) => /-of-/.test(x) && (!only.length || only.includes(x))).sort()) {
  const { manifest } = await import(pathToFileURL(join(PK, n, 'src', 'manifest.js')).href);
  const casesFile = join(PK, n, 'evals', 'cases.json');
  const data = JSON.parse(readFileSync(casesFile, 'utf8')); const cases = data.cases || data;
  const base = cases.find((c) => !c.id.startsWith('intl-') && argFiles(c.args).length && c.expect && (c.expect.equals || c.expect.contains));
  if (!base) continue;
  const kinds = kindsByArg(manifest, base.tool);
  const added = [];
  for (const lang of ['de', 'ja']) {
    const dir = join(PK, n, 'fixtures', 'intl', lang); mkdirSync(dir, { recursive: true });
    const args = JSON.parse(JSON.stringify(base.args));
    for (const [arg, file] of argFiles(base.args)) {
      const def = manifest.sources[kinds.get(arg)]; if (!def) continue;
      const out = localise(readFileSync(join(PK, n, file), 'utf8'), def, lang);
      const target = join(dir, basename(file)); const rel = `fixtures/intl/${lang}/${basename(file)}`;
      let buf; try { buf = encodeText(out.text, MARKETS[lang].enc); } catch { buf = encodeText(out.text, 'utf-8'); }
      if (!existsSync(target) || !readFileSync(target).equals(buf)) { if (check) { console.log(`${n}: ${rel} is stale`); stale++; } else writeFileSync(target, buf); }
      const swap = (v) => (v === file ? rel : Array.isArray(v) ? v.map(swap) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, swap(x)])) : v);
      args[arg] = swap(args[arg]);
    }
    added.push({ id: `intl-${lang}-${base.id}`, tool: base.tool, args, expect: base.expect, note: `${lang === 'de' ? 'German' : 'Japanese'} export of the same data (fixtures/intl/${lang}); must match the English case "${base.id}".` });
  }
  if (!check) writeFileSync(join(PK, n, 'fixtures', 'intl', 'README.md'), README);
  const kept = cases.filter((c) => !c.id.startsWith('intl-'));
  const next = [...kept, ...added];
  const txt = JSON.stringify({ ...(Array.isArray(data) ? {} : data), cases: next }, null, 2) + '\n';
  if (readFileSync(casesFile, 'utf8') !== txt) { if (check) { console.log(`${n}: evals/cases.json lacks the intl cases`); stale++; } else writeFileSync(casesFile, txt); }
}
if (check && stale) process.exit(1);
console.log(check ? 'intl fixtures up to date' : 'intl fixtures written');
