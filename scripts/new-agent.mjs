#!/usr/bin/env node
// Fairwire package boilerplate for the agents in scripts/agents.json: package.json, bin,
// index, demo, test runner, licence, changelog, and the shared tests (MCP stdio, argument
// docs, evals, the contract tests, accepted exceptions and masking). The agent's logic,
// manifest, fixtures, eval cases and domain tests are written by hand.
//
//   node scripts/new-agent.mjs                  every agent in agents.json (keeps hand-written files)
//   node scripts/new-agent.mjs fairwire-network-traffic  only these
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const list = JSON.parse(readFileSync(join(repo, 'scripts', 'agents.json'), 'utf8'));
const only = process.argv.slice(2);
const corePkg = JSON.parse(readFileSync(join(repo, 'packages/fairwire-core/package.json'), 'utf8'));

for (const [name, description, kw] of list.filter(([n]) => !only.length || only.includes(n))) {
  const root = join(repo, 'packages', name);
  const write = (f, text, { keep = false } = {}) => { const p = join(root, f); if (keep && existsSync(p)) return; mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); };
  const title = name.split('-').map((w, i) => (i === 1 ? w : w[0].toUpperCase() + w.slice(1))).join(' ');
  const pkgFile = join(root, 'package.json');
  const old = existsSync(pkgFile) ? JSON.parse(readFileSync(pkgFile, 'utf8')) : {};
  write('package.json', JSON.stringify({
    name, version: old.version || '0.1.0', description: `${title}: ${description}`, type: 'module', license: 'MIT', author: 'Kurt Francisco', engines: { node: '>=20' },
    main: 'src/index.js', exports: { '.': './src/index.js', './package.json': './package.json' }, bin: { [name]: `bin/${name}.js` },
    files: ['src', 'bin', 'fixtures', 'evals', 'README.md', 'CHANGELOG.md', 'LICENSE'],
    scripts: { test: 'node scripts/run-tests.cjs', demo: `node bin/${name}.js demo`, eval: `node bin/${name}.js eval` },
    dependencies: { 'fairwire-core': `^${corePkg.version}` },
    repository: { type: 'git', url: 'git+https://github.com/fpavia111-creator/fairwire-agents.git', directory: `packages/${name}` },
    homepage: `https://github.com/fpavia111-creator/fairwire-agents/tree/main/packages/${name}#readme`,
    bugs: { url: 'https://github.com/fpavia111-creator/fairwire-agents/issues' },
    keywords: ['mcp', 'mcp-server', 'it-operations', 'network', 'fairwire', ...kw.split(',').filter(Boolean)],
    ...(old.mcpName ? { mcpName: old.mcpName } : {}),
  }, null, 2) + '\n');
  write(`bin/${name}.js`, `#!/usr/bin/env node\nimport { fileURLToPath } from 'node:url';\nimport { main } from 'fairwire-core';\nimport { manifest } from '../src/manifest.js';\nimport { demo } from '../src/demo.js';\n\nmain(manifest, { bin: '${name}', demo, evalFile: fileURLToPath(new URL('../evals/cases.json', import.meta.url)) });\n`);
  write('src/index.js', `export { manifest } from './manifest.js';\nexport * from './logic.js';\n`, { keep: true });
  write('src/demo.js', `import { fileURLToPath } from 'node:url';\nimport { readFileSync } from 'node:fs';\nimport { standardDemo } from 'fairwire-core';\n\n// The demo runs the eval case "check-totals" and the agent's draft on the fictional fixtures.\nconst cases = JSON.parse(readFileSync(new URL('../evals/cases.json', import.meta.url), 'utf8')).cases;\nconst base = cases.find((c) => c.id === 'check-totals');\nconst explain = cases.find((c) => /_explain$/.test(c.tool) && !c.expect.status);\nconst draft = cases.find((c) => /_draft_/.test(c.tool) && c.approve);\n\nexport async function demo(manifest) {\n  const refused = manifest.tools.filter((t) => (manifest.policy.rules.find((r) => r.tool === t.name) || {}).decision === 'block')[0];\n  await standardDemo(manifest, fileURLToPath(new URL('../fixtures', import.meta.url)), {\n    title: '${title} demo', args: base.args,\n    explain: explain ? { label: 'Explain one finding', args: explain.args } : null,\n    draft: draft ? { label: 'Draft the note for a person', args: draft.args } : null,\n    refused: refused ? refused.name : null,\n  });\n}\n`, { keep: true });
  write('scripts/run-tests.cjs', readFileSync(join(repo, 'packages/fairwire-core/scripts/run-tests.cjs'), 'utf8'));
  write('LICENSE', readFileSync(join(repo, 'LICENSE'), 'utf8'));
  write('CHANGELOG.md', `# Changelog\n\n## 0.1.0 (unreleased)\n\n- First version (Fairwire ver 1).\n`, { keep: true });
  write('test/contract.test.js', `// Shared contract checks on this agent's own manifest, fixtures and eval cases. Generated by scripts/new-agent.mjs.
import { fileURLToPath } from 'node:url';
import { agentContract } from 'fairwire-core/testkit';
import { manifest } from '../src/index.js';

agentContract({ manifest, casesFile: fileURLToPath(new URL('../evals/cases.json', import.meta.url)) });
`);
  write('test/shared.test.js', `// Shared checks every Fairwire agent passes. Generated by scripts/new-agent.mjs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runEvalFile, undocumentedArgs, ONE_CLICK_CATEGORIES } from 'fairwire-core';
import { manifest } from '../src/index.js';

const bin = fileURLToPath(new URL('../bin/${name}.js', import.meta.url));
const fixtures = fileURLToPath(new URL('../fixtures', import.meta.url));

test('every tool argument is described and every enum has a type', () => {
  assert.deepEqual(undocumentedArgs(manifest), []);
  const walk = (s, path) => { if (!s || typeof s !== 'object') return; if (s.enum) assert.ok(s.type, \`\${path} enum has no type\`); for (const [k, v] of Object.entries(s.properties || {})) walk(v, \`\${path}.\${k}\`); if (s.items) walk(s.items, \`\${path}[]\`); };
  for (const t of manifest.tools) walk(t.inputSchema, t.name);
});

test('one-click categories are never allow, and the default is block', () => {
  for (const t of manifest.tools) if (ONE_CLICK_CATEGORIES.includes(t.category)) { const r = manifest.policy.rules.find((x) => x.tool === t.name); assert.ok(r && r.decision !== 'allow', t.name); }
  assert.deepEqual(manifest.policy.rules.at(-1), { ...manifest.policy.rules.at(-1), tool: '*', decision: 'block' });
});

test('private evals all pass, at least fifteen of them', async () => {
  const r = await runEvalFile(manifest, fileURLToPath(new URL('../evals/cases.json', import.meta.url)));
  for (const c of r.results) assert.ok(c.pass, \`\${c.id}: \${c.fails.join('; ')}\`);
  assert.ok(r.total >= 15, \`at least fifteen eval cases (has \${r.total})\`);
});

test('stdio MCP: initialize, list, refuse an unknown tool, write the audit log', async () => {
  const state = mkdtempSync(join(tmpdir(), '${name}-mcp-'));
  const child = spawn(process.execPath, [bin, 'mcp', '--root', fixtures, '--state-dir', state], { stdio: ['pipe', 'pipe', 'pipe'] });
  let buf = ''; const waiting = new Map(); let id = 0;
  child.stdout.on('data', (d) => { buf += d; let i; while ((i = buf.indexOf('\\n')) >= 0) { const line = buf.slice(0, i); buf = buf.slice(i + 1); if (!line.trim()) continue; const m = JSON.parse(line); const w = waiting.get(m.id); if (w) { waiting.delete(m.id); w(m); } } });
  const request = (method, params) => new Promise((resolve, reject) => { const my = ++id; const t = setTimeout(() => reject(new Error('timeout ' + method)), 10000); waiting.set(my, (m) => { clearTimeout(t); resolve(m); }); child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: my, method, params }) + '\\n'); });
  try {
    const init = await request('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'smoke', version: '0' } });
    assert.equal(init.result.serverInfo.name, '${name}');
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\\n');
    const list = await request('tools/list', {});
    const names = list.result.tools.map((t) => t.name);
    for (const t of manifest.tools) assert.ok(names.includes(t.name), t.name);
    const blocked = await request('tools/call', { name: 'shell_exec', arguments: { cmd: 'whoami' } });
    assert.equal(blocked.result.isError, true);
    assert.ok(existsSync(join(state, 'audit.jsonl')));
  } finally { child.kill(); }
});
`);
  write('test/memory.test.js', `// Accepted exceptions and personal-data masking, on this agent's own eval case "check-totals". Generated by scripts/new-agent.mjs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, cpSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AgentRuntime } from 'fairwire-core';
import { manifest } from '../src/index.js';

const here = fileURLToPath(new URL('..', import.meta.url));
const cases = JSON.parse(readFileSync(join(here, 'evals', 'cases.json'), 'utf8')).cases;
const base = cases.find((c) => c.id === 'check-totals');
const prefix = manifest.tools[0].name.replace(/_check$/, '');
const sandbox = () => { const d = mkdtempSync(join(tmpdir(), \`\${manifest.name}-mem-\`)); cpSync(join(here, 'fixtures'), join(d, 'fixtures'), { recursive: true }); return d; };

test('a finding a named person accepts as known leaves the open count, and nothing changes before the click', async () => {
  const root = sandbox(); const rt = new AgentRuntime(manifest, { root, stateDir: join(root, '.st') });
  const before = await rt.call(\`\${prefix}_check\`, base.args);
  assert.equal(before.status, 'executed', before.reason);
  const first = before.result.items[0]; assert.ok(first, 'the base case has at least one finding');
  const l = await rt.call(\`\${prefix}_learn\`, { kind: 'known_exception', value: { code: first.code, key: first.key, note: 'reviewed in the test' } });
  assert.equal(l.status, 'executed', l.reason);
  const still = await rt.call(\`\${prefix}_check\`, base.args); assert.equal(still.result.open, before.result.open, 'a proposed fact changes nothing');
  const ask = await rt.call(\`\${prefix}_accept_learning\`, { id: l.result.fact.id, decision: 'accept' }); assert.equal(ask.status, 'needs_approval');
  rt.approvals.approve(ask.approval_id, 'Pat Example');
  const ok = await rt.call(\`\${prefix}_accept_learning\`, { id: l.result.fact.id, decision: 'accept' }); assert.equal(ok.status, 'executed', ok.reason);
  const after = await rt.call(\`\${prefix}_check\`, base.args);
  assert.equal(after.result.accepted, 1); assert.equal(after.result.open, before.result.open - 1);
  assert.ok(after.memory_applied && after.memory_applied.length === 1);
});

test('personal fields in the files and e-mail addresses never reach the model', async () => {
  const root = sandbox(); const rt = new AgentRuntime(manifest, { root, audit: false });
  const r = await rt.call(\`\${prefix}_check\`, { ...base.args, limit: 5000 });
  assert.equal(r.status, 'executed', r.reason);
  const text = JSON.stringify(r.result);
  assert.doesNotMatch(text, /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}/, 'an e-mail address reached the model');
  const ctx = rt.context(base.args, \`\${prefix}_check\`);
  for (const [arg, file] of Object.entries(base.args)) {
    const kind = Object.entries(manifest.sources || {}).find(([, d]) => (d.args || []).includes(arg));
    if (!kind || typeof file !== 'string') continue;
    const piiFields = Object.entries(kind[1].fields).filter(([, fd]) => fd && fd.pii).map(([f]) => f);
    for (const row of ctx.records(file, kind[0])) for (const f of piiFields) { const v = String(row[f] ?? '').trim(); if (v.length >= 4) assert.ok(!text.includes(v), \`\${f} value reached the model\`); }
  }
});
`);
  console.log(`wrote ${name}`);
}
